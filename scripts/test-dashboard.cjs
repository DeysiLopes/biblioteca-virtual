const runBrowserTest=require("./browser-test.cjs");

const test=async function(){
  const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const check=(value,message)=>{ if(!value) throw new Error(message); };
  const errors=[];
  window.addEventListener("error",e=>errors.push(e.message));
  window.addEventListener("unhandledrejection",e=>errors.push(String(e.reason)));
  try{
    await sleep(1200);
    registerSW=async()=>{}; pullSync=async()=>{}; loadCatalog=async()=>{};
    const saved=new Map();
    putOf=async(name,value)=>saved.set(`${name}:${value.id??value.k}`,structuredClone(value));
    allOf=async(name)=>[...saved.entries()].filter(([key])=>key.startsWith(name+":")).map(([,value])=>structuredClone(value));
    persistReading=async(books,entry)=>{ for(const b of books) await putOf("books",b); if(entry) await putOf("diary",entry); };
    await init();
    const yesterday=new Date(); yesterday.setDate(yesterday.getDate()-1);
    const oldDate=yesterday.toISOString().slice(0,10);
    BOOKS=[{id:"dashboard-test",title:"Livro teste",status:"Lendo",paginas:390,paginasLidas:0,inicio:oldDate,resenha:"Resenha preservada",citacoes:[{id:"quote",text:"Citação",page:42}]}];
    DIARY=[{id:"old-10",bookId:BOOKS[0].id,date:oldDate,pages:10,ts:1},{id:"old-100",bookId:BOOKS[0].id,date:today(),pages:100,ts:2}];
    for(const b of BOOKS) await putOf("books",b);
    for(const d of DIARY) await putOf("diary",d);
    const stats=()=>[...document.querySelectorAll("#dstats .v")].map(el=>el.textContent);
    const draw=()=>{ renderDiary(); renderStats(); };
    draw();
    check(stats().join("|")==="0 pág|0 dias|0 pág|0","Progresso zero não zerou o dashboard: "+stats().join("|"));
    check(!document.querySelector("#week .wcol.today .v").textContent&&[...document.querySelectorAll("#week .wcol .v")].every(el=>!el.textContent),"Gráfico semanal ainda conta o histórico de 10 e 100 páginas");
    check(document.querySelector("#statsShelf").textContent.includes("Hoje 0 págs"),"Estante usa outra contagem diária");
    BOOKS[0].paginasLidas=100; await putOf("books",BOOKS[0]); draw();
    check(stats()[0]==="100 pág"&&stats()[3]==="1","Histórico acima do progresso atual não foi limitado");
    openBook(BOOKS[0].id);
    fdStatus="Lido";
    document.querySelector("#bPagesLidas").value="0";
    await saveBook(document.querySelector("#panel"),BOOKS[0].id); await sleep(600);
    check(stats().join("|")==="0 pág|0 dias|0 pág|0"&&DIARY.length===2,"Zerar pelo modal deixou valores antigos ou apagou o histórico");
    check(document.querySelector("#statsShelf").textContent.includes("Hoje 0 págs"),"Filtro vazio deixou o contador da Estante desatualizado");
    fdStatus="todos";
    const resetEpoch=BOOKS[0].readingEpoch;
    check(resetEpoch>0,"Reset não marcou o início de um novo histórico ativo");
    await loadData(); draw();
    check(stats()[0]==="0 pág"&&stats()[3]==="0","Recarregar reativou os testes antigos");
    openBook(BOOKS[0].id);
    document.querySelector("#bPagesLidas").value="5";
    await saveBook(document.querySelector("#panel"),BOOKS[0].id); await sleep(600);
    check(stats().join("|")==="5 pág|1 dia|5 pág|1","Recomeçar somou as leituras antigas: "+stats().join("|"));
    check(document.querySelector("#week .wcol.today .v").textContent==="5","Gráfico semanal não mostra somente a nova leitura");
    check(document.querySelector("#statsShelf").textContent.includes("Hoje 5 págs"),"Estante não acompanha o reset");
    check(DIARY.length===3&&DIARY.some(d=>d.id==="old-10")&&DIARY.some(d=>d.id==="old-100"),"Reset removeu os dados antigos");
    const active=DIARY.find(d=>d.pages===5);
    check(active.readingEpoch===BOOKS[0].readingEpoch&&active.readingEpoch>=resetEpoch,"Nova sessão pertence ao histórico errado");
    const payload=buildSyncPayload();
    check(payload.books[BOOKS[0].id].readingEpoch===BOOKS[0].readingEpoch&&payload.diary.find(d=>d.id===active.id).readingEpoch===active.readingEpoch,"Sincronização perdeu a marcação do reset");
    const merged=mergePayload({v:1,books:{},diary:[{id:"replayed",bookId:BOOKS[0].id,date:today(),pages:500,ts:3}]},payload);
    DIARY=merged.diary; draw();
    check(stats()[0]==="5 pág"&&stats()[3]==="1","Sincronizar registros antigos reativou o dashboard");
    const book=Object.assign({},BOOKS[0]);
    BOOKS=mergeCatalog([{id:book.id,title:book.title,paginas:390}],[book]); draw();
    check(stats()[0]==="5 pág","Atualizar catálogo perdeu o estado do reset");
    BOOKS.push({id:"other",title:"Outro livro",status:"Lendo",paginasLidas:3,readingEpoch:999,citacoes:[]});
    DIARY.push({id:"other-entry",bookId:"other",date:today(),pages:3,ts:4,readingEpoch:999});
    draw();
    check(stats()[0]==="8 pág"&&stats()[2]==="8 pág"&&stats()[3]==="2","Dashboard não combina corretamente dois livros ativos");
    openBook(book.id);
    document.querySelector("#bPagesLidas").value="0";
    await saveBook(document.querySelector("#panel"),book.id); await sleep(600);
    check(stats()[0]==="3 pág"&&stats()[2]==="3 pág"&&stats()[3]==="1","Reset de um livro zerou as leituras de outro");
    check(BOOKS[0].resenha==="Resenha preservada"&&BOOKS[0].citacoes.length===1,"Reset alterou resenha ou citações");
    check(errors.length===0,errors.join("; "));
    document.body.innerHTML='<pre id="testout">'+JSON.stringify({ok:true,test:"dashboard",width:innerWidth})+'</pre>';
  }catch(error){
    document.body.innerHTML='<pre id="testout">'+JSON.stringify({ok:false,error:error.message,errors})+'</pre>';
  }
};
runBrowserTest(test).catch(error=>{ console.error(error); process.exitCode=1; });
