const runBrowserTest=require("./browser-test.cjs");

const test=async function(){
  const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const check=(value,message)=>{ if(!value) throw new Error(message); };
  const errors=[];
  window.addEventListener("error",e=>errors.push(e.message));
  window.addEventListener("unhandledrejection",e=>errors.push(String(e.reason)));
  try{
    await sleep(1200);
    registerSW=async()=>{}; pullSync=async()=>{}; loadCatalog=async()=>{};
    const saved=new Map();
    putOf=async(name,value)=>saved.set(`${name}:${value.id??value.k}`,structuredClone(value));
    allOf=async(name)=>[...saved.entries()].filter(([key])=>key.startsWith(name+":")).map(([,value])=>structuredClone(value));
    delOf=async(name,id)=>saved.delete(`${name}:${id}`);
    persistReading=async(books,entry)=>{ for(const b of books) await putOf("books",b); if(entry) await putOf("diary",entry); };
    await init();
    check(!document.querySelector("#dform,#fpages,#fbook"),"O formulário antigo do Diário ainda existe");
    BOOKS=[{id:"legacy",title:"Legado",paginasLidas:0,status:"Lendo",citacoes:[]},{id:"known",title:"Acumulado",paginasLidas:100,status:"Lendo",citacoes:[]}];
    for(const b of BOOKS) await putOf("books",b);
    await putOf("diary",{id:"legacy-entry",bookId:"legacy",pages:10,date:today(),ts:1});
    await putOf("diary",{id:"known-entry",bookId:"known",pages:10,date:today(),ts:1});
    await putOf("diary",{id:"known-old-test",bookId:"known",pages:100,date:today(),ts:2});
    await loadData();
    check(BOOKS[0].paginasLidas===0&&BOOKS[1].paginasLidas===100,"Carregar o histórico somou páginas que não foram informadas no modal");
    check(DIARY.length===3,"Carregamento apagou registros antigos");
    saved.clear();
    BOOKS=[{id:"reading-test",title:"Livro teste",author:"Teste",status:"Lendo",tipo:"Lazer",paginas:200,paginasLidas:40,inicio:"2026-09-01",fim:"",nota:4,resenha:"Resenha preservada",citacoes:[{id:"quote",text:"Uma citação",page:7}],comentarios:"Comentário original",cover:""},{id:"other-test",title:"Outro livro",author:"Teste",status:"Quero ler",paginas:100,paginasLidas:0,citacoes:[],cover:""}];
    for(const b of BOOKS) await putOf("books",b);
    META={}; DIARY=[];
    renderFilters(); renderShelves(); renderDiary();
    const current=()=>BOOKS.find(b=>b.id==="reading-test");
    const panelFields=()=>[...document.querySelectorAll("#panel input,#panel select,#panel textarea")].map(el=>el.id).sort().join(",");
    const saveModal=async(id=current().id)=>{ await saveBook(document.querySelector("#panel"),id); await sleep(600); };
    document.querySelector('.book-card[data-id="reading-test"]').click();
    check(!document.querySelector("#pStars,#bResenha,#bEntries,#panel .cite-btn"),"Modal ainda mostra nota, resenha, citações ou registros");
    const fields=panelFields();
    check(fields==="bComent,bFim,bId,bInicio,bPagesLidas,bStatus,bTipo,bTotal","Campos inesperados no modal: "+fields);
    check(document.querySelector("#pProgress").textContent.includes("40 / 200"),"Progresso inicial ausente");
    const pages=document.querySelector("#bPagesLidas");
    check(pages.value==="40","Modal não preenche o total salvo");
    pages.value="55"; pages.dispatchEvent(new Event("input",{bubbles:true}));
    check(document.querySelector("#pPerc").textContent==="28%","Prévia da barra somou o total ao valor anterior");
    document.querySelector("#bComent").value="Comentário atualizado";
    const persist=persistReading;
    persistReading=async()=>{ throw new Error("Falha simulada"); };
    await saveBook(document.querySelector("#panel"),current().id);
    check(current().paginasLidas===40&&DIARY.length===0&&!document.querySelector('#panel [data-act="save"]').disabled,"Falha ao salvar alterou o estado ou bloqueou o modal");
    persistReading=persist;
    await Promise.all([saveBook(document.querySelector("#panel"),current().id),saveBook(document.querySelector("#panel"),current().id)]);
    await sleep(600);
    check(current().paginasLidas===55,"Informar 55 não salvou exatamente 55");
    check(DIARY.length===1&&DIARY[0].pages===15,"Registro automático duplicou páginas ou registrou o total como sessão");
    check(current().nota===4&&current().resenha==="Resenha preservada"&&current().citacoes.length===1,"Modal apagou campos removidos");
    check(!document.querySelector("#diaryList .elog,#diaryList .entryedit,#diaryList input"),"Diário mantém registros separados ou outro ponto de preenchimento");
    check(document.querySelector('.nbook[data-id="reading-test"] .reading-progress').textContent.includes("55 / 200"),"Diário não mostra o progresso compartilhado");
    switchTab("diary");
    document.querySelector('.nbook[data-id="reading-test"] .bt').click();
    check(panelFields()===fields,"Modal do Diário difere do modal da Estante");
    check(document.querySelector("#bComent").value==="Comentário atualizado"&&document.querySelector("#bTipo").value==="Lazer"&&document.querySelector("#bInicio").value==="2026-09-01","Dados gerais divergem entre as abas");
    check(document.querySelector("#bPagesLidas").value==="55","Modal do Diário usa outro total");
    document.querySelector("#bTotal").value="250";
    await saveModal();
    check(current().paginasLidas===55&&DIARY.length===1,"Salvar o mesmo total duplicou páginas");
    check(buildSyncPayload().books[current().id].paginas===250,"Total de páginas não é sincronizado");
    check(mergeCatalog([{id:current().id,title:"Livro teste",paginas:200}],[current()])[0].paginas===250,"Recarga do catálogo perdeu o total editado");
    document.querySelector("#btnAddDiary").click();
    check(panelFields()===fields&&!document.querySelector("#dform"),"Registrar leitura abriu outro formulário");
    check(document.querySelector("#bPagesLidas").value==="55","Registrar leitura não usa o total salvo");
    document.querySelector("#bPagesLidas").value="75";
    await saveModal();
    check(current().paginasLidas===75&&DIARY.length===2,"Registrar pelo Diário não salvou o valor informado");
    await putOf("diary",{id:"old-test",bookId:current().id,pages:1000,date:today(),note:"Teste antigo",ts:1});
    await loadData(); renderDiary();
    check(current().paginasLidas===75&&DIARY.length===3,"Recarregar somou o teste antigo ou apagou o histórico");
    const inflated=Object.assign({},current(),{paginasLidas:110});
    await putOf("books",inflated); BOOKS[0]=inflated;
    openBook(current().id);
    document.querySelector("#bPagesLidas").value="100";
    await saveModal();
    await loadData(); renderDiary();
    check(current().paginasLidas===100&&DIARY.length===3,"Corrigir 110 para 100 voltou a somar o histórico");
    check(document.querySelector('.nbook[data-id="reading-test"] .reading-progress').textContent.includes("100 / 250"),"Diário não respeitou a correção do modal");
    check((await allOf("diary")).some(d=>d.id==="old-test"&&d.pages===1000),"Correção apagou dados antigos");
    openBook(current().id);
    document.querySelector("#bPagesLidas").value="250";
    document.querySelector("#bFim").value="2026-10-02";
    await saveModal();
    check(current().paginasLidas===250&&current().status==="Lido"&&current().fim==="2026-10-02","Concluir a leitura não atualizou status e data");
    const count=DIARY.length;
    openBook(current().id);
    document.querySelector("#bPagesLidas").value="245";
    await saveModal();
    await loadData();
    check(current().paginasLidas===245&&current().status==="Lendo"&&!current().fim&&DIARY.length===count,"Corrigir o total recriou páginas ou deixou status desatualizado");
    openBook(current().id);
    document.querySelector("#bId").value="other-test";
    document.querySelector("#bId").dispatchEvent(new Event("change",{bubbles:true}));
    check(document.querySelector("#bPagesLidas").value==="0","Trocar de livro reutilizou o total anterior");
    document.querySelector("#bPagesLidas").value="12";
    await saveModal("other-test");
    check(BOOKS[1].paginasLidas===12&&current().paginasLidas===245,"Editar outro livro alterou o livro anterior");
    switchTab("shelf");
    document.querySelector('.book-card[data-id="reading-test"]').click();
    check(document.querySelector("#pProgress").textContent.includes("245 / 250"),"Estante ficou com progresso antigo");
    document.querySelector("#bPagesLidas").value="";
    await saveBook(document.querySelector("#panel"),current().id);
    check(current().paginasLidas===245,"Campo vazio zerou o progresso");
    document.querySelector("#bPagesLidas").value="-5";
    await saveBook(document.querySelector("#panel"),current().id);
    check(current().paginasLidas===245&&document.querySelector("#modal").classList.contains("open"),"Páginas inválidas alteraram o progresso");
    check((await allOf("books")).find(b=>b.id===current().id).paginasLidas===245,"Estado persistido diverge da interface");
    check(errors.length===0,errors.join("; "));
    document.body.innerHTML='<pre id="testout">'+JSON.stringify({ok:true,test:"leitura",width:innerWidth})+'</pre>';
  }catch(error){
    document.body.innerHTML='<pre id="testout">'+JSON.stringify({ok:false,error:error.message,errors})+'</pre>';
  }
};
runBrowserTest(test).catch(error=>{ console.error(error); process.exitCode=1; });
