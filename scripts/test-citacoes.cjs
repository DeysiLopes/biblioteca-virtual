    check(Math.abs(quoteRect.x+quoteRect.width/2-innerWidth/2)<3&&Math.abs(quoteRect.y+quoteRect.height/2-innerHeight/2)<36,"Citação não está no centro da tela");
    check(getComputedStyle(overlay.querySelector(".fic-quote")).textAlign==="center","Citação no fichário não está centralizada");
