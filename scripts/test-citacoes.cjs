    await init();
    BOOKS=[{id:"quote-test",title:"Livro & <teste>",author:"Autora",resenha:"Resenha preservada",paginasLidas:100,paginas:390,status:"Lendo",citacoes:Array.from({length:16},(_,i)=>({id:`quote-${i}`,text:`Citação ${i+1} & <texto>\nSegunda linha.`,page:i+10,ts:i+1})),cover:""}];
    META={};
    renderDiary();
    document.querySelector('[data-cites="quote-test"]').click();
    const overlay=document.querySelector("#fichario");
    check(overlay.classList.contains("open"),"Fichário não abriu");
    check(overlay.querySelectorAll('.fic-tab[role="tab"]').length===16,"Cada citação precisa de uma aba");
    check(overlay.querySelector(".fic-rings"),"Argolas do fichário ausentes");
    check(overlay.querySelector('[role="tab"][aria-selected="true"]').dataset.cid==="quote-0","Primeira aba não selecionada");
    overlay.querySelector('[data-cid="quote-1"]').click();
    check(overlay.querySelector(".fic-quote").textContent===BOOKS[0].citacoes[1].text,"Aba não mostra a citação correta");
    overlay.querySelector('[data-cid="quote-1"]').dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowDown",bubbles:true,cancelable:true}));
    check(overlay.querySelector('[role="tab"][aria-selected="true"]').dataset.cid==="quote-2","Navegação por teclado não selecionou a aba seguinte");
    overlay.querySelector('[data-cid="quote-2"]').dispatchEvent(new KeyboardEvent("keydown",{key:"End",bubbles:true,cancelable:true}));
    check(overlay.querySelector('[aria-selected="true"]').dataset.cid==="quote-15"&&overlay.querySelector(".fic-tabs").scrollTop>0,"Abas fora da tela não podem ser alcançadas");
    overlay.querySelector('[data-cid="quote-2"]').click();
    overlay.querySelector("#ficEdit").click();
    check(overlay.classList.contains("focused"),"Edição não colocou a folha em foco");
    const text=overlay.querySelector("#cText"),page=overlay.querySelector("#cPage");
    check(document.activeElement===text&&text.value===BOOKS[0].citacoes[2].text,"Editor não tem foco ou perdeu o texto");
    check([...overlay.querySelectorAll(".fic-tab")].every(tab=>tab.disabled),"Trocar de aba pode perder o rascunho");
    overlay.getAnimations({subtree:true}).forEach(animation=>animation.finish());
    const rect=overlay.querySelector(".fic-shell").getBoundingClientRect();
    check(rect.left>=0&&rect.right<=innerWidth+1&&rect.top>=0&&rect.bottom<=innerHeight+1,"Editor centralizado está fora da tela");
    check(Math.abs(rect.x+rect.width/2-innerWidth/2)<2,"Editor não está centralizado");
    page.value="";
    await saveCitacao("quote-test");
    check(BOOKS[0].citacoes.length===16&&overlay.classList.contains("focused"),"Página obrigatória não foi validada");
